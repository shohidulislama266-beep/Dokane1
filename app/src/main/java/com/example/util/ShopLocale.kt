    fun toBengaliDigits(input: String): String {
        val sb = StringBuilder(input.length)
        for (ch in input) {
            if (ch in '0'..'9') {
                sb.append(banglaDigits[ch - '0'])
            } else {
                sb.append(ch)
            }
        }
        return sb.toString()
    }

    fun toAsciiDigits(input: String): String {
        val sb = StringBuilder(input.length)
        for (ch in input) {
            val idx = banglaDigits.indexOf(ch)
            if (idx >= 0) {
                sb.append(('0'.code + idx).toChar())
            } else {
                sb.append(ch)
            }
        }
        return sb.toString()
    }

    fun digits(raw: String, lang: AppLanguage): String =
        if (lang == AppLanguage.BN) toBengaliDigits(raw) else raw

    fun formatMoney(amount: Double, lang: AppLanguage): String {
        val isNegative = amount < 0.0
        val absVal = abs(amount)
        val formatted = String.format(Locale.US, "%.2f", absVal)
        val text = if (formatted.endsWith(".00")) {
            String.format(Locale.US, "%.0f", absVal)
        } else {
            formatted
        }
        val sign = if (isNegative) "-" else ""
        return if (lang == AppLanguage.BN) {
            sign + toBengaliDigits(text) + " " + CURRENCY
        } else {
            sign + CURRENCY + " " + text
        }
    }

    fun formatMoneyFixed2(amount: Double, lang: AppLanguage): String {
        val isNegative = amount < 0.0
        val absVal = abs(amount)
        val text = String.format(Locale.US, "%.2f", absVal)
        val sign = if (isNegative) "-" else ""
        return if (lang == AppLanguage.BN) {
            sign + toBengaliDigits(text) + " " + CURRENCY
        } else {
            sign + CURRENCY + " " + text
        }
    }

    fun formatSignedMoney(amount: Double, lang: AppLanguage): String {
        val prefix = if (amount > 0.0) "+" else if (amount < 0.0) "-" else ""
        return prefix + formatMoney(abs(amount), lang)
    }

    fun formatCompactMoney(amount: Double, lang: AppLanguage): String {
        val sign = if (amount < 0.0) "-" else ""
        val absVal = abs(amount)
        return if (absVal >= 1000.0) {
            val scaled = String.format(Locale.US, "%.1f", absVal / 1000.0).trimEnd('0').trimEnd('.')
            if (lang == AppLanguage.BN) {
                "$sign${toBengaliDigits(scaled)}হাজার"
            } else {
                "$sign${scaled}k"
            }
        } else {
            val whole = absVal.toInt().toString()
            sign + digits(whole, lang)
        }
    }

    fun formatNumber(number: Long, lang: AppLanguage): String =
        digits(number.toString(), lang)

    fun formatNumber(number: Int, lang: AppLanguage): String =
        formatNumber(number.toLong(), lang)

    fun formatNumber(number: Double, lang: AppLanguage): String {
        val safe = if (abs(number) < 1e-9) 0.0 else number
        val bd = java.math.BigDecimal.valueOf(safe)
            .setScale(4, java.math.RoundingMode.HALF_UP)
            .stripTrailingZeros()
        val raw = bd.toPlainString()
        return digits(raw, lang)
    }

    fun formatDecimal(value: Double, decimals: Int = 2, lang: AppLanguage): String {
        val raw = String.format(Locale.US, "%.${decimals}f", value)
        return digits(raw, lang)
    }

    fun formatPercent(value: Double, decimals: Int = 1, lang: AppLanguage): String {
        val raw = String.format(Locale.US, "%.${decimals}f", value)
        return "${digits(raw, lang)}%"
    }

