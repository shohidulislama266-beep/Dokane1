    private fun pad2(v: Int): String = if (v < 10) "0$v" else v.toString()

    private fun calOf(timestampMillis: Long): Calendar =
        Calendar.getInstance().apply { timeInMillis = timestampMillis }

    private fun formatTime12(cal: Calendar, lang: AppLanguage, padHour: Boolean = true): String {
        val hour24 = cal.get(Calendar.HOUR_OF_DAY)
        val hour12 = when (val h = hour24 % 12) {
            0 -> 12
            else -> h
        }
        val min = cal.get(Calendar.MINUTE)
        val amPm = if (hour24 < 12) get("am", lang) else get("pm", lang)
        val hStr = if (padHour) pad2(hour12) else hour12.toString()
        val timeRaw = "$hStr:${pad2(min)}"
        return "${digits(timeRaw, lang)} $amPm"
    }

    fun formatTimeOnly(timestampMillis: Long, lang: AppLanguage): String {
        val cal = calOf(timestampMillis)
        return formatTime12(cal, lang, padHour = false)
    }

    fun formatDateOnly(timestampMillis: Long, lang: AppLanguage): String {
        val cal = calOf(timestampMillis)
        val day = pad2(cal.get(Calendar.DAY_OF_MONTH))
        val monthIdx = cal.get(Calendar.MONTH).coerceIn(0, 11)
        val year = cal.get(Calendar.YEAR).toString()
        val monthStr = if (lang == AppLanguage.BN) bnMonthsShort[monthIdx] else enMonthsShort[monthIdx]
        return "${digits(day, lang)} $monthStr ${digits(year, lang)}"
    }

    fun formatDateOnlyFullMonth(timestampMillis: Long, lang: AppLanguage): String {
