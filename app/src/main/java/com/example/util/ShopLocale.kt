    /**
     * Converts any mixed-language string to plain Bangla with Bengali numerals and zero Latin ASCII letters.
     * Used exclusively for Simple & Father Mode UI and restricted exports.
     */
    fun plainBanglaText(raw: String, fallback: String = "তথ্য"): String {
        val trimmed = raw.trim()
        if (trimmed.isEmpty()) return fallback
        val directCat = displayCategory(trimmed, AppLanguage.BN)
        var text = if (directCat != trimmed) directCat else trimmed
        val directUnit = displayUnit(text, AppLanguage.BN)
        if (directUnit != text) text = directUnit
        plainBnTokenMap.forEach { (en, bn) ->
            val regex = Regex("\\b${Regex.escape(en)}\\b", RegexOption.IGNORE_CASE)
            text = text.replace(regex, bn)
        }
        // Replace any leftover ASCII word tokens cleanly so zero English words remain
        text = text.replace(Regex("[A-Za-z]+(?:[-_][A-Za-z0-9]+)*"), "")
            .replace(Regex("\\s{2,}"), " ")
            .replace("()", "")
            .replace("[]", "")
            .trim()
            .trim('-', '•', '|', ':')
            .trim()
        val withBnDigits = toBengaliDigits(text)
        return withBnDigits.ifBlank { fallback }
    }

