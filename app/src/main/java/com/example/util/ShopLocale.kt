    fun formatRelativeDayHeader(timestampMillis: Long, todayKey: String, yesterdayKey: String, itemDayKey: String, lang: AppLanguage): String {
        val cal = calOf(timestampMillis)
        val dayNoPad = cal.get(Calendar.DAY_OF_MONTH).toString()
        val monthIdx = cal.get(Calendar.MONTH).coerceIn(0, 11)
        val yearStr = cal.get(Calendar.YEAR).toString()
        val monthStr = if (lang == AppLanguage.BN) bnMonthsShort[monthIdx] else enMonthsShort[monthIdx]
        val datePart = "${digits(dayNoPad, lang)} $monthStr ${digits(yearStr, lang)}"
        return when (itemDayKey) {
            todayKey -> "${get("today_label", lang)} · $datePart"
            yesterdayKey -> "${get("yesterday_label", lang)} · $datePart"
            else -> {
                val dow = cal.get(Calendar.DAY_OF_WEEK).coerceIn(1, 7)
                val weekday = if (lang == AppLanguage.BN) bnWeekdaysShort[dow] else enWeekdaysShort[dow]
                "$weekday · $datePart"
            }
        }
    }

    fun formatTimeAgo(lastMillis: Long?, lang: AppLanguage): String {
        if (lastMillis == null) return ""
        val diffMin = ((System.currentTimeMillis() - lastMillis) / 60000L).coerceAtLeast(0L)
        return when {
            diffMin < 1L -> get("just_now", lang)
            diffMin < 60L -> format("minutes_ago", lang, diffMin)
            else -> format("hours_ago", lang, diffMin / 60L)
        }
    }

