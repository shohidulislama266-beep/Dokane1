    fun format(key: String, lang: AppLanguage, vararg args: Any): String {
        val template = get(key, lang)
        val normalizedArgs = args.map { arg ->
            when (arg) {
                is Int -> formatNumber(arg.toLong(), lang)
                is Long -> formatNumber(arg, lang)
                is Double -> formatNumber(arg, lang)
                is Float -> formatNumber(arg.toDouble(), lang)
                else -> arg
            }
        }.toTypedArray()
        return try {
            val formatted = String.format(Locale.US, template, *normalizedArgs)
            if (lang == AppLanguage.BN) toBengaliDigits(formatted) else formatted
        } catch (_: Exception) {
            template
        }
    }

